/** Капотасана: колени на полу, локти на полу за пятками, ладони держат стопы, голова у стоп. */
/**
 * Капотасана: deep backbend на голенях, руки к стопам — C-дуга груди, не доска.
 */
/** C-дуга капотасаны: параллельная lean-лента, не «гора» у макушки дуги. */
function kapotaTrunk() {
  const cx = 108;
  const cy = 168;
  const ro = 78;
  const ri = 62;
  const a0 = (-165 * Math.PI) / 180;
  const a1 = (-40 * Math.PI) / 180;
  const n = 7;
  const outer = [];
  const inner = [];
  for (let i = 0; i <= n; i++) {
    const a = a0 + ((a1 - a0) * i) / n;
    outer.push([cx + ro * Math.cos(a), cy + ro * Math.sin(a)]);
  }
  for (let i = n; i >= 0; i--) {
    const a = a0 + ((a1 - a0) * i) / n;
    const widen = i === n ? 2.4 : i === n - 1 ? 1.2 : 0;
    inner.push([cx + (ri - widen) * Math.cos(a), cy + (ri - widen) * Math.sin(a)]);
  }
  return [...outer, ...inner.slice(1, -1)];
}


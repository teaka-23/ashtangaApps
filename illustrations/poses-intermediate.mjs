/**
 * Свои позы второй серии (Нади Шодхана).
 * Профиль лицом в +x. Фронт — только если иначе жест не читается
 * (воротца, гомукха, титтибхасана в стороны, свободные руки стойки).
 * Шорты короткие, на тазу. Стопы: плоско / flex / tops / вдоль голени.
 */
import { draw, svgDocument } from './figure.mjs';

const { leg, thigh, shin, arm, torso, shortsFrame, head, headFront, shadow, groundLine } = draw;

function doc(parts) {
  return svgDocument([groundLine(), ...parts].join('\n'));
}

function S(hip, up, front, thighs, opt = {}) {
  return shortsFrame(hip, up, front, {
    rise: 8,
    half: 9,
    legLen: 17,
    inline: true,
    thighs,
    ...opt,
  });
}


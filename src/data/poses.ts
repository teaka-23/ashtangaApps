export interface Figure {
  /** Центр головы */
  head: [number, number];
  headR?: number;
  /** Точка дришти (куда смотрит) — если задана, рисуется маркер на голове */
  drishti?: [number, number];
  /** Сегментированные руки: [плечо, локоть, кисть] для левой и правой */
  arms?: {
    left: [[number, number], [number, number], [number, number]];
    right: [[number, number], [number, number], [number, number]];
  };
  /** Сегментированные ноги: [бедро, колено, стопа] для левой и правой */
  legs?: {
    left: [[number, number], [number, number], [number, number]];
    right: [[number, number], [number, number], [number, number]];
  };
  /** @deprecated Используйте arms/legs. Старый формат для совместимости. */
  strokes?: [number, number][][];
  /** Контур торса (плечи → таз), рисуется залитым. Точки по кругу */
  torso?: [number, number][];
  /** Y линии пола (не рисуется, если не задан) */
  ground?: number;
}

export interface PoseDef {
  figures: Figure[];
}

const f = (
  head: [number, number],
  arg2?: number | [number, number][][],
  arg3?: [number, number][] | number,
  arg4?: [number, number][] | Figure['arms'],
  arg5?: Figure['legs'],
  arg6?: [number, number],
): Figure => {
  // Старый формат: f(head, strokes, ground, torso)
  // Новый формат: f(head, ground, torso, arms, legs, drishti)
  if (Array.isArray(arg2) && arg2.length > 0 && Array.isArray(arg2[0]) && Array.isArray(arg2[0][0])) {
    // arg2 = strokes (number[][][])
    return {
      head,
      strokes: arg2 as [number, number][][],
      ground: typeof arg3 === 'number' ? arg3 : undefined,
      torso: (Array.isArray(arg3) ? arg3 : arg4) as [number, number][] | undefined,
    };
  }
  // Новый формат
  return {
    head,
    ground: typeof arg2 === 'number' ? arg2 : undefined,
    torso: (Array.isArray(arg2) ? arg2 : arg3) as [number, number][] | undefined,
    arms: arg4 as Figure['arms'],
    legs: arg5,
    drishti: arg6,
  };
};


/** Режим стопы: иначе эвристика по голени в AsanaFigure */
export type FootMode = 'flat' | 'tucked' | 'tops' | 'flex' | 'along';

export interface Figure {
  /** Центр головы */
  head: [number, number];
  headR?: number;
  /** Точка дришти (куда смотрит) — если задана, рисуется маркер на голове */
  drishti?: [number, number];
  /** Сегментированные руки: [плечо, локоть, кисть] для левой и правой */
  arms?: {
    left: [[number, number], [number, number], [number, number]];
    right: [[number, number], [number, number], [number, number]];
  };
  /** Сегментированные ноги: [бедро, колено, стопа] для левой и правой */
  legs?: {
    left: [[number, number], [number, number], [number, number]];
    right: [[number, number], [number, number], [number, number]];
  };
  /** Контур торса (плечи → таз), рисуется залитым. Точки по кругу */
  torso?: [number, number][];
  /** Y линии пола (не рисуется, если не задан) */
  ground?: number;
  /** Явный режим стоп (планка / урдхва / стоя) */
  feet?: FootMode;
}

export interface PoseDef {
  figures: Figure[];
  /** Индекс основного кадра для превью в списке. По умолчанию — средний */
  mainFrame?: number;
}

